import { formatNumber as f } from '../../format';
import { randomInt } from '../../random';
import type { ChartBlock } from '../../types';
import { choiceOptions } from '../scenario/options';
import { approx, pick } from '../scenario/text';
import type { ScenarioTemplate } from '../template';
import { niceAxis } from './axis';
import { looksCharted, unitOption, until, years } from './charts';

interface Setting {
  intro: string;
  title: string;
  unit: string;
  /** The whole, for prompts: "revenue". */
  whole: string;
  parts: [string, string, string];
  /** Typical size of one part in a year. */
  part: [number, number];
}

const SETTINGS: Setting[] = [
  {
    intro: 'A homeware retailer sells through its own stores, its website and department-store concessions.',
    title: 'Revenue by channel',
    unit: 'Revenue, $m',
    whole: 'revenue',
    parts: ['Stores', 'Online', 'Concessions'],
    part: [20, 90],
  },
  {
    intro: 'A regional utility generates electricity from gas, wind and solar and is reviewing how its mix has changed.',
    title: 'Electricity generated by source',
    unit: 'Output, TWh',
    whole: 'output',
    parts: ['Gas', 'Wind', 'Solar'],
    part: [12, 60],
  },
  {
    intro: 'A city-centre hotel group tracks room nights sold by type of guest.',
    title: 'Room nights by guest type',
    unit: 'Room nights, thousands',
    whole: 'room nights',
    parts: ['Business', 'Leisure', 'Groups'],
    part: [15, 70],
  },
];

/**
 * Stacked bars over four years with every segment and each year’s total
 * labelled. Tier 1 asks one segment’s share of a year; tier 2 a segment’s
 * growth; tier 3 how many percentage points its share moved.
 */
export const stackedMix: ScenarioTemplate = {
  id: 'stacked-mix',
  skill: 'stacked-bar-charts',
  tiers: [1, 2, 3],
  build(tier, random) {
    const s = pick(random, SETTINGS);
    const labels = years(random, 4);

    return until(() => {
      const series = s.parts.map((name) => {
        let v = randomInt(random, s.part[0], s.part[1]);
        const trend = randomInt(random, -8, 25);
        return {
          name,
          values: labels.map(() => {
            const now = Math.round(v);
            v = v * (1 + (trend + randomInt(random, -6, 6)) / 100);
            return now;
          }),
        };
      });
      const totals = labels.map((_, k) => series.reduce((sum, x) => sum + x.values[k]!, 0));
      const axis = niceAxis(0, Math.max(...totals), 6);
      // Every segment tall enough to hold its printed value.
      if (series.some((x) => x.values.some((v) => v < axis.max * 0.1))) return null;

      const x = randomInt(random, 0, 2);
      const part = s.parts[x]!;
      const chart: ChartBlock = {
        type: 'chart',
        chart: 'stacked-bar',
        title: s.title,
        unit: `${s.unit}; totals above the bars`,
        categories: labels,
        series,
        axis,
        labelled: true,
        decimals: 0,
        highlight: x,
        barNotes: totals.map((t) => f(t)),
      };
      const intro = { type: 'paragraph' as const, text: s.intro };
      const values = series[x]!.values;

      if (tier === 1) {
        const k = randomInt(random, 0, 3);
        const truth = (values[k]! / totals[k]!) * 100;
        if (looksCharted(truth, chart)) return null;
        const { options, correctIndex, correct } = choiceOptions(truth, random, {
          format: unitOption('', '%'),
          finestStep: 0.1,
          traps: [(values[k]! / (totals[k]! - values[k]!)) * 100],
        });
        return {
          targetTimeMs: 60_000,
          prompt: `What share of ${labels[k]} ${s.whole} came from ${part}?`,
          context: [intro, chart],
          answer: { kind: 'choice', options, correctIndex },
          solution: [`${part} in ${labels[k]}: ${f(values[k]!)} of ${f(totals[k]!)}`, `Share: ${f(values[k]!)} ÷ ${f(totals[k]!)} = ${approx(truth)}%`, `Closest option: ${correct}`],
          shortcut: `Use the total printed above the bar rather than adding segments: ${f(values[k]!)} ÷ ${f(totals[k]!)} ≈ ${approx(truth / 100)} of the year.`,
        };
      }

      const a = values[0]!;
      const b = values[3]!;
      if (tier === 2) {
        const truth = (b / a - 1) * 100;
        if (truth < 5 || looksCharted(truth, chart)) return null;
        const { options, correctIndex, correct } = choiceOptions(truth, random, {
          format: unitOption('', '%'),
          finestStep: 0.1,
          // The growth of the whole instead of the part.
          traps: [(totals[3]! / totals[0]! - 1) * 100, b - a],
        });
        return {
          targetTimeMs: 75_000,
          prompt: `By what percentage did ${s.whole} from ${part} grow from ${labels[0]} to ${labels[3]}?`,
          context: [intro, chart],
          answer: { kind: 'choice', options, correctIndex },
          solution: [`${part}: ${labels[0]} = ${f(a)}, ${labels[3]} = ${f(b)}`, `Growth: ${f(b)} ÷ ${f(a)} − 1 = ${approx(truth)}%`, `Closest option: ${correct}`],
          shortcut: `Ignore the totals; only the ${part} segments matter. The rise is ${f(b - a)} on ${f(a)}.`,
        };
      }

      const share0 = (a / totals[0]!) * 100;
      const share3 = (b / totals[3]!) * 100;
      const truth = share3 - share0;
      // A rise of at least 3.5 points, so options a point apart stay close neighbours.
      if (truth < 3.5 || looksCharted(truth, chart)) return null;
      const { options, correctIndex, correct } = choiceOptions(truth, random, {
        format: unitOption('', ' points'),
        finestStep: 0.1,
        // The segment's own growth rate, a different measure.
        traps: [(b / a - 1) * 100],
      });
      return {
        targetTimeMs: 105_000,
        prompt: `By how many percentage points did the share of ${s.whole} from ${part} rise from ${labels[0]} to ${labels[3]}?`,
        context: [intro, chart],
        answer: { kind: 'choice', options, correctIndex },
        solution: [
          `${labels[0]} share: ${f(a)} ÷ ${f(totals[0]!)} = ${approx(share0)}%`,
          `${labels[3]} share: ${f(b)} ÷ ${f(totals[3]!)} = ${approx(share3)}%`,
          `Change: ${approx(share3)} − ${approx(share0)} = ${approx(truth)} points`,
          `Closest option: ${correct}`,
        ],
        shortcut: `Work each share to one decimal place and subtract; percentage points are a difference of shares, not a growth rate.`,
      };
    });
  },
};
